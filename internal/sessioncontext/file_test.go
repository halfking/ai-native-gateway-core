func TestReduceFilePreservesMiddleFactAndRecoversRaw(t *testing.T) {
	store, err := largebody.NewStore(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	defer store.Close()
	prefix := `{"messages":[{"role":"system","content":"Protect the billing configuration."},{"role":"user","content":"Maintain billing."},{"role":"assistant","tool_calls":[{"id":"a","type":"function","function":{"name":"read","arguments":"{}"}}]},{"role":"tool","tool_call_id":"a","content":"`
	suffix := `"},{"role":"user","content":"Find the billing database port and config path."}],"model":"at-the-end"}`
	// The input is generated by readers; no giant source byte slice is created.
	src := io.MultiReader(strings.NewReader(prefix), io.LimitReader(repeatingText(`unrelated line\n`), 999_996), strings.NewReader(`\nBilling database port 6432, /srv/billing/db.yaml\n`), io.LimitReader(repeatingText(`unrelated line\n`), 999_996), strings.NewReader(suffix))
	ref, err := store.Capture(context.Background(), largebody.Identity{TenantID: "tenant", SessionID: "session"}, src)
	if err != nil {
		t.Fatal(err)
	}
	got, report, err := Reduce(context.Background(), store, ref, 64<<10)
	if err != nil {
		t.Fatal(err)
	}
	if !json.Valid(got) || len(got) > 64<<10 || report.SourceBytes != ref.Size || !report.Reduced {
		t.Fatalf("bad result: %+v %d", report, len(got))
	}
	for _, want := range []string{"Protect the billing configuration.", "Maintain billing.", "6432", "/srv/billing/db.yaml", "Find the billing database port and config path.", "at-the-end"} {
		if !bytes.Contains(got, []byte(want)) {
			t.Errorf("lost %s", want)
		}
	}
	recovered, err := store.Recover(context.Background(), ref.Identity)
	if err != nil || recovered.SHA256 != ref.SHA256 {
		t.Fatalf("restore %+v %v", recovered, err)
	}
}
