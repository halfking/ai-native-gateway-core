func TestJSONStringExcerptDecodesEscapesAndUnicode(t *testing.T) {
	raw := `"prefix\n\u4e2d\uD83D\uDE00 quote=\" slash=\\\tend"`
	got, err := stringExcerpt(context.Background(), strings.NewReader(raw), "", 1024)
	if err != nil {
		t.Fatal(err)
	}
	var want string
	_ = json.Unmarshal([]byte(raw), &want)
	if got != want {
		t.Fatalf("got %q want %q", got, want)
	}
}
func repeatingText(text string) io.Reader { return &repeatText{text: text} }

type repeatText struct {
	text string
	pos  int
}

func (r *repeatText) Read(p []byte) (int, error) {
	for i := range p {
		p[i] = r.text[r.pos%len(r.text)]
		r.pos++
	}
	return len(p), nil
}

type cancelExcerptReader struct {
	r      io.Reader
	cancel context.CancelFunc
	read   int
}

func (r *cancelExcerptReader) Read(p []byte) (int, error) {
	n, e := r.r.Read(p)
	r.read += n
	if r.read >= 100000 {
		r.cancel()
	}
	return n, e
}
func TestJSONStringExcerptCancelsDuringRead(t *testing.T) {
	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()
	r := &cancelExcerptReader{r: strings.NewReader(`"` + strings.Repeat("x", 200000) + `"`), cancel: cancel}
	if _, err := stringExcerpt(ctx, r, "query", 1024); err != context.Canceled {
		t.Fatalf("cancel ignored: %v; read=%d", err, r.read)
	}
}
func TestExtractiveQualityChineseCodeAndLongLines(t *testing.T) {
	facts := []struct{ fact, query string }{
		{"账单数据库端口是6432，配置文件路径为/srv/billing/db.yaml。", "请找出账单数据库端口和配置文件路径"},
		{"The retry budget is 7, config /opt/agent/retry.json.", "What is the retry budget config?"},
		{"func BillingPort() int { return 6432 } // config: /srv/billing/db.yaml", "Find BillingPort config"},
	}
	for _, tc := range facts {
		text := strings.Repeat("x", 3000) + " " + tc.fact + " " + strings.Repeat("x", 5000)
		out := sampleText(text, tc.query, 1024)
		if !strings.Contains(out, tc.fact) {
			t.Fatalf("lost source fact for %q: %q", tc.query, out)
		}
	}
}

