func TestFileMetadataBoundsEmptyNestedStructures(t *testing.T) {
	row := `{"parts":[` + strings.TrimSuffix(strings.Repeat(`{},`, 1024), ",") + `]}`
	text := `{"content":[` + strings.TrimSuffix(strings.Repeat(row+",", 1024), ",") + `]}`
	r := strings.NewReader(text)
	if b, err := fileMetadata(context.Background(), r, largebody.Span{Length: int64(len(text))}, 0); err == nil {
		t.Fatalf("accepted unbounded structural metadata: %d", len(b))
	}
}
