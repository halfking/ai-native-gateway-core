-- 6. promote 函数（638 守卫形态）
-- =============================================

CREATE OR REPLACE FUNCTION public.promote_session_memora_hot_to_partition(
    retention_window interval DEFAULT '8 hours',
    batch_size integer DEFAULT 5000
)
RETURNS TABLE(moved_count bigint) AS $$
DECLARE
    cutoff_ts timestamptz;
BEGIN
    IF retention_window IS NULL OR retention_window <= interval '0 seconds' THEN
        RAISE EXCEPTION 'retention_window must be positive';
    END IF;
    IF batch_size IS NULL OR batch_size < 1 THEN
        RAISE EXCEPTION 'batch_size must be >= 1';
    END IF;
    cutoff_ts := now() - retention_window;
    IF NOT pg_try_advisory_xact_lock(hashtext('public.promote_session_memora_hot_to_partition')) THEN
        RETURN QUERY SELECT 0::bigint;
        RETURN;
    END IF;
    WITH to_move AS (
        SELECT id, session_id, tenant_id, client_env, initial_context,
               created_at, partition_date
        FROM public.session_memora_hot
        WHERE created_at < cutoff_ts
        ORDER BY created_at
        LIMIT batch_size
        FOR UPDATE SKIP LOCKED
    ),
    inserted AS (
        INSERT INTO public.session_memora
            (id, session_id, tenant_id, client_env, initial_context,
             created_at, partition_date)
        SELECT id, session_id, tenant_id, client_env, initial_context,
               created_at, partition_date
        FROM to_move
        ON CONFLICT (id, partition_date) DO NOTHING
        RETURNING id, partition_date
    ),
    deleted AS (
        DELETE FROM public.session_memora_hot h
        USING inserted i
        WHERE h.id = i.id AND h.partition_date = i.partition_date
        RETURNING 1
    )
    SELECT count(*) INTO moved_count FROM deleted;
    RETURN QUERY SELECT moved_count;
END;
$$ LANGUAGE plpgsql;

