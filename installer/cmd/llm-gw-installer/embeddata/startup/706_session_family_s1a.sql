-- 1. session_memora
-- =============================================

CREATE TABLE IF NOT EXISTS public.session_memora (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    session_id TEXT NOT NULL,
    tenant_id TEXT NOT NULL,
    client_env JSONB,            -- 客户端类型/版本/入口/项目/agent
    initial_context JSONB,       -- system prompt digest+指纹、初始消息指纹、可用工具清单
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    partition_date DATE NOT NULL DEFAULT CURRENT_DATE,
    PRIMARY KEY (id, partition_date),
    UNIQUE (tenant_id, session_id, partition_date)
) PARTITION BY RANGE (partition_date);

CREATE INDEX IF NOT EXISTS idx_session_memora_session
    ON public.session_memora (session_id, partition_date DESC);

ALTER TABLE public.session_memora ENABLE ROW LEVEL SECURITY;

