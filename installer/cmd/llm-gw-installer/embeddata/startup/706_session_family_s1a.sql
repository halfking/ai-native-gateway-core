-- Migration 706: 存储优化方案 v2 · S1a —— 六表族补全（三新表 + sessions 补列）
--
-- docs/03-design/04-data-design/storage-optimization-plan.md §4 S1a 行：
--   session_memora / session_censors / session_tools 三新表 + sessions 补列。
--
-- 三新表职责（方案 §1）：
--   session_memora  —— 会话初始环境/上下文快照（首 turn 一次写入，insert-only）；
--                      与同实例 kxmemory 产品的 memora_* 表零接触（跨产品边界禁令）。
--   session_censors —— SmartSaniGuard 可逆脱敏映射落库（现 Redis-only、TTL 30min
--                      即永久丢失）；original_encrypted 为应用层 AES-GCM，密钥未
--                      配置时为 NULL（降级只存 type+占位符）。
--   session_tools   —— 承接 domains/toolexecution 写链（134 形状 + turn_no +
--                      月分区化）。审计事实（2026-09-14 本机）：migration 134 属
--                      domain 通道、本地两账本均无记录，tool_executions 表不存在，
--                      写链一直缺表；切到本表同时修复该缺口。tool_call_events
--                      （8 行、无 session、零读者）废弃不迁。
--
-- 分区惯例沿用 430：partition_date 存日粒度（calendarDate(ts)），月分区
-- [_2026_09 ...)；hot 表 + promote 函数沿用 614/615/638 惯例，PartitionManager
-- 经 bg.ensureSpecs/promoteSpecs 注册（Go 侧同提交）。
--
-- Compatibility: 纯增量建表 + 可空补列，对既有数据零回填、零锁风险。
-- down: DROP 三新表族 + sessions 补列（账本行保留，append-only）。

