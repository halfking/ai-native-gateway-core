-- 5. ensure 函数（月分区；bg.ensureSpecs 注册）
-- =============================================

CREATE OR REPLACE FUNCTION public.ensure_session_family_partitions(target_date DATE DEFAULT CURRENT_DATE)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
    month_start DATE := DATE_TRUNC('month', target_date)::DATE;
    month_end DATE := (DATE_TRUNC('month', target_date) + INTERVAL '1 month')::DATE;
    partition_suffix TEXT := TO_CHAR(month_start, 'YYYY_MM');
BEGIN
    EXECUTE format(
        'CREATE TABLE IF NOT EXISTS public.session_memora_%s PARTITION OF public.session_memora
         FOR VALUES FROM (%L) TO (%L)',
        partition_suffix, month_start, month_end
    );
    EXECUTE format(
        'CREATE TABLE IF NOT EXISTS public.session_censors_%s PARTITION OF public.session_censors
         FOR VALUES FROM (%L) TO (%L)',
        partition_suffix, month_start, month_end
    );
    EXECUTE format(
        'CREATE TABLE IF NOT EXISTS public.session_tools_%s PARTITION OF public.session_tools
         FOR VALUES FROM (%L) TO (%L)',
        partition_suffix, month_start, month_end
    );
    RAISE NOTICE 'Created session family partitions for %', partition_suffix;
END;
$$;

COMMENT ON FUNCTION public.ensure_session_family_partitions(DATE) IS
    'Ensure monthly partitions for session_memora/session_censors/session_tools.
     Called by bg.PartitionManager ensureSpecs (migration 706).';

SELECT public.ensure_session_family_partitions(CURRENT_DATE);
SELECT public.ensure_session_family_partitions((CURRENT_DATE + INTERVAL '1 month')::DATE);

