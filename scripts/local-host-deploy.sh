#!/usr/bin/env bash
# ============================================================================
# scripts/local-host-deploy.sh — 本机版本化部署 / 回退 / 状态 (245 风格)
#
# 学习 245 部署 (/opt/llm-gateway-go/releases/<v>/{gateway,web,version.json,...})
# 的"atomic symlink 切换 + 验证后才算 verified + 自动 prune 旧版本"模型,
# 但跑在本地 macOS 上 —— 直接 host 启动 gateway 二进制, 不走 systemd。
#
# 目录布局: see scripts/local-host-layout-helper.sh
#
# 用法:
#   bash scripts/local-host-deploy.sh deploy           # 编译并部署当前 HEAD
#   bash scripts/local-host-deploy.sh deploy --keep N  # 保留 N 个 verified 版本
#   bash scripts/local-host-deploy.sh start            # 启动当前 active
#   bash scripts/local-host-deploy.sh stop             # 停止当前进程
#   bash scripts/local-host-deploy.sh restart          # 重启当前 active
#   bash scripts/local-host-deploy.sh status           # 进程 + healthz + 当前版本
#   bash scripts/local-host-deploy.sh list             # 所有 bundle + 标记 active/verified
#   bash scripts/local-host-deploy.sh rollback <ver>   # 回退到指定 verified 版本
#   bash scripts/local-host-deploy.sh logs [N]         # tail -n N ~/Downloads/llm-gateway-files/logs/gateway.stdout.log
#   bash scripts/local-host-deploy.sh verify           # 重跑 L1 验证 (不重启)
#   bash scripts/local-host-deploy.sh cleanup          # 停止并删除当前 active bundle
#   bash scripts/local-host-deploy.sh env              # 输出当前 active 的 env (供 source)
# ============================================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

# shellcheck source=local-host-layout-helper.sh
source "$SCRIPT_DIR/local-host-layout-helper.sh"

# ── Colors ───────────────────────────────────────────────────────────────
RED=$'\033[0;31m'; GREEN=$'\033[0;32m'; YELLOW=$'\033[1;33m'
BLUE=$'\033[0;34m'; CYAN=$'\033[0;36m'; NC=$'\033[0m'
log()   { echo -e "${BLUE}[lh-deploy]${NC} $*"; }
ok()    { echo -e "${GREEN}  ✓${NC} $*"; }
warn()  { echo -e "${YELLOW}  ⚠${NC} $*"; }
err()   { echo -e "${RED}  ✗${NC} $*" >&2; }
section()  { echo -e "\n${CYAN}━━━ $* ━━━${NC}"; }

# ── Defaults ──────────────────────────────────────────────────────────────
KEEP_VERIFIED=3
PORT=8781
ACTION="${1:-}"

# ── Parse args ────────────────────────────────────────────────────────────
shift || true
while [[ $# -gt 0 ]]; do
  case "$1" in
    --keep) KEEP_VERIFIED="$2"; shift 2 ;;
    --port) PORT="$2"; shift 2 ;;
    --root) LLM_GATEWAY_FILES_ROOT="$2"; export LLM_GATEWAY_FILES_ROOT; shift 2 ;;
    -h|--help)
      sed -n '2,30p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
      exit 0
      ;;
    *) err "unknown arg: $1"; exit 1 ;;
  esac
done

# ── Pre-flight ────────────────────────────────────────────────────────────
lh_require_root >/dev/null

# Try to discover the local PG password from env-injector. Fall back to
# kxpass (the r112 compose default) only if no secret is loaded.
if [[ -z "${COMMON_PG_SUPERUSER_PASS:-}" ]]; then
  # shellcheck disable=SC1090 # loader path is env-dependent (per-machine), shellcheck can't follow it
  source ~/workspace/ai-native-tools/envs/loader.sh --project llm-gateway-go --server 115.29.212.252 2>/dev/null || true
fi
LOCAL_PG_PASS="${COMMON_PG_SUPERUSER_PASS:-kxpass}"

# Load version.json SSOT (git_tag + build_seq + git_sha → version string).
VERSION_JSON="$PROJECT_ROOT/version.json"
if [[ ! -f "$VERSION_JSON" ]]; then
  err "version.json not found at $VERSION_JSON"
  exit 1
fi
GIT_TAG=$(python3 -c "import json;print(json.load(open('$VERSION_JSON'))['git_tag'])")
BUILD_SEQ=$(python3 -c "import json;print(json.load(open('$VERSION_JSON'))['build_seq'])")
GIT_SHA=$(python3 -c "import json;print(json.load(open('$VERSION_JSON'))['git_sha'])")
VERSION="${GIT_TAG}.${BUILD_SEQ}"

log "version: $VERSION  (git_tag=$GIT_TAG build_seq=$BUILD_SEQ git_sha=$GIT_SHA)"

# ── Env contract (mirrors local-deploy-test.sh gateway_env()) ─────────────
# These are written into each bundle's env.sh so the runner sources the right
# values without leaking secrets through /tmp.
emit_env_block() {
  local bundle_dir=$1
  cat >"$bundle_dir/env.sh" <<ENVEOF
# Auto-generated by scripts/local-host-deploy.sh for $VERSION
export LLM_GATEWAY_LISTEN=":$PORT"
export LLM_GATEWAY_ENV="\${LLM_GATEWAY_ENV:-local}"
export LOG_LEVEL="\${LOG_LEVEL:-info}"
export LLM_GATEWAY_DATABASE_URL="\${LLM_GATEWAY_DATABASE_URL:-postgres://llm_gateway:${LOCAL_PG_PASS}@127.0.0.1:5432/llm_gateway?sslmode=disable}"
export LLM_GATEWAY_REDIS_ADDR="\${LLM_GATEWAY_REDIS_ADDR:-127.0.0.1:16379}"
export LLM_GATEWAY_REDIS_PASSWORD="\${LLM_GATEWAY_REDIS_PASSWORD:-}"
export LLM_GATEWAY_CREDENTIAL_ENCRYPTION_KEY="\${LLM_GATEWAY_CREDENTIAL_ENCRYPTION_KEY:-AwoRGB8mLTQ7QklQV15lbHN6gYiPlp2kq7K5wMfO1dw}"
export LLM_GATEWAY_JWT_SECRET="\${LLM_GATEWAY_JWT_SECRET:-local-dev-secret-do-not-use-in-production-12345678}"
export LLM_GATEWAY_ADMIN_API_KEY="\${LLM_GATEWAY_ADMIN_API_KEY:-local-admin-test-token-do-not-use-in-production}"
export LLM_GATEWAY_CORS_ORIGINS="\${LLM_GATEWAY_CORS_ORIGINS:-*}"
export LLM_GATEWAY_ATTACHMENT_DIR="$(lh_layout_vars | sed -n 's/^attachments_dir=//p')"
export LLM_GATEWAY_BACKUP_DIR="$(lh_layout_vars | sed -n 's/^backups_dir=//p')"
export LLM_GATEWAY_RAW_LOG_DIR="$(lh_layout_vars | sed -n 's/^raw_logs_dir=//p')"
export LLM_GATEWAY_UPSTREAM="\${LLM_GATEWAY_UPSTREAM:-http://localhost:18080}"
export LLM_GATEWAY_SEED_ADMIN_PASSWORD="\${LLM_GATEWAY_SEED_ADMIN_PASSWORD:-Veritrans&9527}"
export LLM_GATEWAY_SYSTEM_MONITOR_ENABLED="\${LLM_GATEWAY_SYSTEM_MONITOR_ENABLED:-true}"
export OPS_NODE_REGION="\${OPS_NODE_REGION:-local}"
export OPS_COLLECT_URL="\${OPS_COLLECT_URL:-https://llm.kxpms.cn}"
export LLM_GATEWAY_STATIC_DIR="\${LLM_GATEWAY_STATIC_DIR:-./web}"
