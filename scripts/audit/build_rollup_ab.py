#!/usr/bin/env python3
"""Build the interleaved A/B harness for the stats rollup aggregation (READ-ONLY).

Why this exists (§143.27, runbook
`docs/06-deployment/04-runbooks/runbooks/2026-10-04-ursm-write-amplification-measurement.md`):

The `stats_usage_daily` rollup (`domains/stats/daily_monthly_rollup.go`) was being
killed by the role-level `statement_timeout=30s` roughly 45 times a day. To decide
whether "raise the timeout" is the right fix, the statement's real cost had to be
measured — and the cost turned out to be dominated by **cold-cache random index
probes**, not by the aggregation.

The two arms differ in exactly one predicate:

  V1 (current) : JOIN stats_event_dedup ON (event_id, occurred_at)
  V2 (variant) : the same, PLUS a time range on the dedup side
                 -> lets the planner consider a Parallel Hash Join (sequential read)

The CTE, the SELECT list, the 6-arm UNION ALL and the GROUP BY are
**byte-identical** to the production statement: the SQL is extracted mechanically
from the Go source and only the INSERT header and the ON CONFLICT tail are removed,
so the measurement is READ-ONLY and does not drift from production.

Discipline: warm-up first, then interleaved ABAB x N, report median and within-arm
spread.  Each arm needs its **own** cold window if the cold case is being measured
(a sequential warm-up would warm the other arm's pages).

Usage:
    python3 build_rollup_ab.py [--from 2026-10-17T00:00:00Z] [--to 2026-10-20T00:00:00Z]
                               [--rounds 4] [--out /tmp/rollup_ab.sql]
                               [--cold-pair FROM1,TO1,FROM2,TO2]
"""

import argparse
import os
import re
import sys

GO = "domains/stats/daily_monthly_rollup.go"


def extract_daily_insert_sql(path):
    src = open(path, encoding="utf-8").read()
    m = re.search(r"const dailyInsertSQL = `(.*?)`\n", src, re.S)
    if not m:
        sys.exit("BLOCKED: dailyInsertSQL not found in " + path)
    sql = m.group(1)

    cte_end = sql.index("\n)\nINSERT INTO stats_usage_daily")
    cte = sql[:cte_end + 2]                      # "WITH latest AS ( ... )"
    rest = sql[cte_end + 2:]

    sel = rest.index("SELECT\n\t\t(occurred_at AT TIME ZONE 'UTC')::date")
    body = rest[sel:]
    body = body[:body.index("ON CONFLICT (day_utc,")].rstrip()
    return cte, body


def bound(cte, body, w0, w1):
    """Bind $1/$2 to literals and return (cte, body) for that window."""
    cte = cte.replace("$1", w0).replace("$2", w1)
    body = body.replace("$1", w0).replace("$2", w1)
    return cte, body


def time_bound_dedup(cte, w0, w1):
    pat = re.compile(r"(WHERE f\.occurred_at >= %s AND f\.occurred_at < %s)" % (
        re.escape(w0), re.escape(w1)))
    m = pat.search(cte)
    if not m:
        sys.exit("BLOCKED: latest-CTE WHERE clause not found")
    return (cte[:m.end()]
            + "\n\t  AND d.occurred_at >= %s AND d.occurred_at < %s" % (w0, w1)
            + cte[m.end():])


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--go", default=GO)
    ap.add_argument("--from", dest="w_from", default="2026-10-17T00:00:00Z")
    ap.add_argument("--to", dest="w_to", default="2026-10-20T00:00:00Z")
    ap.add_argument("--rounds", type=int, default=4)
    ap.add_argument("--out", default="/tmp/rollup_ab.sql")
    ap.add_argument("--cold-pair", default="",
                    help="FROM1,TO1,FROM2,TO2 -- two DISJOINT windows so each arm "
                         "gets its own cold start (a sequential warm-up would warm "
                         "the other arm's pages)")
    args = ap.parse_args()

    w0 = "'%s'::timestamptz" % args.w_from
    w1 = "'%s'::timestamptz" % args.w_to
    cte0, body0 = extract_daily_insert_sql(args.go)

    out = ["-- AUTO-GENERATED by scripts/audit/build_rollup_ab.py",
           "-- READ-ONLY: only the INSERT header and the ON CONFLICT tail were removed;",
           "-- the CTE / SELECT list / UNION ALL / GROUP BY are byte-identical to production.",
           "SET statement_timeout = '600s';",
           "\\timing on",
           "\\pset format unaligned",
           "\\pset tuples_only on",
           ""]

    def emit(label, cte, body):
        out.append("\\echo '%s'" % label)
        out.append("\\o /dev/null")
        out.append(cte + "\n" + body + ";")
        out.append("\\o")
        out.append("")

    if args.cold_pair:
        f1, t1, f2, t2 = args.cold_pair.split(",")
        cte1, body1 = bound(cte0, body0, "'%s'::timestamptz" % f1, "'%s'::timestamptz" % t1)
        cte2, body2 = bound(cte0, body0, "'%s'::timestamptz" % f2, "'%s'::timestamptz" % t2)
        # Each arm gets its own DISJOINT window => each first run is genuinely cold.
        emit("COLD V1-current (own window %s..%s)" % (f1, t1), cte1, body1)
        emit("COLD V2-timebounded-dedup (own window %s..%s)" % (f2, t2),
             time_bound_dedup(cte2, "'%s'::timestamptz" % f2, "'%s'::timestamptz" % t2), body2)
        # Then a WARM repeat of each arm on the SAME window => the cold penalty
        # of each arm is measurable, and the warm numbers are volume-comparable.
        emit("WARM V1-current (same window %s..%s)" % (f1, t1), cte1, body1)
        emit("WARM V2-timebounded-dedup (same window %s..%s)" % (f2, t2),
             time_bound_dedup(cte2, "'%s'::timestamptz" % f2, "'%s'::timestamptz" % t2), body2)
        for r in range(args.rounds):
            emit("ROUND %d V1-current" % (r + 1), cte1, body1)
            emit("ROUND %d V2-timebounded-dedup" % (r + 1),
                 time_bound_dedup(cte2, "'%s'::timestamptz" % f2, "'%s'::timestamptz" % t2), body2)
    else:
        cte, body = bound(cte0, body0, w0, w1)
        cte_v2 = time_bound_dedup(cte, w0, w1)
        for name, c in (("V1-current", cte), ("V2-timebounded-dedup", cte_v2)):
            emit("WARMUP %s" % name, c, body)
        for r in range(args.rounds):
            for name, c in (("V1-current", cte), ("V2-timebounded-dedup", cte_v2)):
                emit("ROUND %d %s" % (r + 1, name), c, body)

    text = "\n".join(out) + "\n"
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote %s (%d bytes)" % (args.out, len(text)))
    print("window %s .. %s ; rounds=%d ; cold_pair=%s"
          % (args.w_from, args.w_to, args.rounds, args.cold_pair or "none"))


if __name__ == "__main__":
    main()
