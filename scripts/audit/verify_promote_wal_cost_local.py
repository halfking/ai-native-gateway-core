def psql(sql, db=DB, stdin=False, check=True):
    """跑一段 SQL。

    ★ stdin=True ⇒ 走 psql 的【**裸 stdin（交互模式）**】（★ 注意：这条路径**没有** `-f`
      ⇒ **不是**脚本模式；★ R102 轮实测：**裸 stdin / `-f -` / `-f /dev/stdin`** 三种
      stdin 读入方式的失败语义**完全一致** ⇒ 叫法差异**不影响结论**）
      ⇒ 里面的多条语句**逐条发送、各自独立事务** ⇒ 「SET x; DROP y;」写在同一行是**合法**的。
      ★★ 而**一条 `-c` 里**写多条 ⇒ 整串当成**一个**隐式事务 ⇒ 「DROP DATABASE cannot run
        inside a transaction block」⇒ 清理**直接失败且静默**。
        ★★ 但「同一 psql 进程的**多条独立 `-c`**」是**合法**的（各自独立事务、SET 对后续生效）
          ⇒ ⇒ 「逐条发送」的准确含义是【**不把两条并进同一条 `-c`**】，
          而**不是**【必须换形态】⇒ ★ 段八 的 shell 腿正是这个形态。
      ★ check=False ⇒ 失败只返回、不 raise ⇒ 用于【清理路径】：
        清理失败不得盖掉真正的错误（与 python 侧 atexit 兜底的约定一致）。
        ★★ 但 check=False ⇒ **失败在调用侧不可见** ⇒ ⇒ 清理路径**必须另查落点**。
    """
    cmd = ["docker", "exec", "-i", "llm-gateway-pg", "psql", "-U", "llm_gateway", "-d", db,
           "-v", "ON_ERROR_STOP=1", "-P", "pager=off", "-t", "-A", "-F", "|"]
    r = subprocess.run(cmd, input=sql, capture_output=True, text=True) if stdin \
        else subprocess.run(cmd + ["-c", sql], capture_output=True, text=True)
    if check and r.returncode != 0:
        print("SQL FAILED rc=%d\n%s\n%s" % (r.returncode, sql[:300], r.stderr[:1000]))
        raise SystemExit(1)
    return r.stdout.strip()


# ★★★ 清理形态（R99 轮 · §19.20.65）——**四处**共用同一套：
#   ① 先 terminate 踢掉占用会话（把「阻塞者」清掉）
#   ② 再【带 statement_timeout】地 DROP
#   ★★ 超时取 **120s**：实测「terminate 之后 DROP 仍要等被 SIGTERM 的后端收尾」
#     可达数十秒（PG 17.10 / 高负载下实测到 89.37s）⇒ ⇒ 15s 会把【合法】的清理
#     砍成「被超时取消」⇒ ⇒ 「清理失败」＝「库泄漏」⇒ ⇒ 与守卫目的**正好相反**。
#   ★★ SET 与 DROP 必须【逐条发送】⇒ ⇒ 必须走 stdin=True 的脚本模式
#     （-c 模式会把两条并进一个隐式事务 ⇒ PG 直接拒绝 ⇒ 清理静默失败）。
#   ★★ WITH (FORCE) 兜住「还有连接没断干净」。
def _drop_db() -> str:
    """回收一次性库（★ 不抛异常 ⇒ 清理失败不得盖掉真正的错误）。"""
    try:
        psql("SELECT pg_terminate_backend(pid) FROM pg_stat_activity WHERE datname = '%s';" % DB,
             db="postgres", check=False)
        out = psql("SET statement_timeout='120s'; DROP DATABASE IF EXISTS %s WITH (FORCE);" % DB,
                   db="postgres", stdin=True, check=False)
        # ★★ R102 轮补：【查落点】——check=False ⇒ 失败在调用侧**不可见**
        #   ⇒ ⇒ 「清理是否真的成功」只能由「库里还有没有」来判
        #   ⇒ ⇒ 与 finally 块里的同形态查询是**同一套**（改一处必须改另一处）。
        left = psql("SELECT 'LEFT=' || count(*) FROM pg_database WHERE datname = '%s';" % DB,
                    db="postgres", check=False).strip()
        if left != "LEFT=0":
            out += "\n[cleanup] ⚠ 回收未完成：%s" % left
        return out
    except Exception as e:  # noqa: BLE001
        return "[cleanup] WARN: %s" % e


# ★ 信号接管（R99 轮 · §19.20.65）⇒ 让 finally 块在【被信号终止】时也真的跑。
#   ★ 实测：python 的 try/finally 在进程被 SIGTERM 终止时【不执行】
#   ⇒ ⇒ 「被 CI / Ctrl-C / 编排器超时杀掉」⇒ 一次性库留下。
#   ★ 手法：处理器【抛异常】⇒ 异常沿栈展开 ⇒ finally 块【真的】执行。
class _Terminated(BaseException):
    """收到 SIGTERM / SIGINT ⇒ 抛出来让 finally 真的跑。"""


def _on_signal(signum, _frame):
    raise _Terminated(f"收到信号 {signum}")


def _install_signal_handlers() -> None:
    """接管 SIGTERM / SIGINT ⇒ 走「异常展开」路径 ⇒ finally 真的跑。"""
    signal.signal(signal.SIGTERM, _on_signal)
    signal.signal(signal.SIGINT, _on_signal)


def wal():
    return int(psql("SELECT wal_bytes FROM pg_stat_wal;").splitlines()[-1])


def build(hot_idx, part_idx):
    # ★ 预清理也走守卫形态（_drop_db）⇒ 与 finally 块同一套（见 _drop_db 的注释）
    # ★★ R102 轮补：原先**返回值被丢弃** ⇒ 预清理失败【当场静默】
    #   ⇒ ⇒ 现在把结果打出来（失败会带 ⚠ 标记）
    #   ⇒ 诚实边界：预清理失败**并非完全无声** ⇒ 后续 CREATE DATABASE 会因「库还在」而失败
    #   ⇒（check=True ⇒ SystemExit(1)）⇒ 但那是**间接**证据，不如当场可见。
    _pre = _drop_db()
    if _pre and ("⚠" in _pre or "WARN" in _pre):
        print("[cleanup] ⚠ 预清理未完全成功：%s" % _pre.strip(), file=sys.stderr)
    psql("CREATE DATABASE %s;" % DB, db="postgres")
    # ★★ 这里的 statement_timeout='300s' 属于【建库 DDL】，**不是**清理语句 ⇒ 不动它
    psql("SET statement_timeout='300s';\n"
         + DDL_TMPL.replace("--HOTIDX--", hot_idx).replace("--PARTIDX--", part_idx), stdin=True)


def fill():
    psql(FILL % (INCOMPRESSIBLE, INCOMPRESSIBLE, INCOMPRESSIBLE, N))


def measure():
    """⇒ (批量 INSERT 的 WAL, promote 的 WAL, 逻辑行宽)"""
    psql("TRUNCATE public.session_bodies_hot; TRUNCATE public.session_bodies;")
    fill()
    rw_b = int(psql("SELECT avg(pg_column_size(t))::bigint FROM public.session_bodies_hot t LIMIT 200;").splitlines()[-1])
    rw = psql("SELECT pg_size_pretty(%d::bigint);" % rw_b)
    # ★ 清场后重灌 ⇒ 测「灌这一批」的 WAL（TRUNCATE 在基线之前，不计入）
    psql("TRUNCATE public.session_bodies_hot; TRUNCATE public.session_bodies;")
    b = wal()
    fill()
    w_ins = wal() - b
    # ★ 复用刚灌的行 ⇒ 测 promote 的 WAL
    b2 = wal()
    psql("SELECT moved_count FROM public.promote_session_bodies_hot_to_partition('1 hour'::interval, 5000);")
    w_pro = wal() - b2
    return w_ins, w_pro, rw, rw_b


def main():
    out = {}
    try:
        for label, hi, pi in [
            ("生产形态：hot 6 索引 / 分区 7 索引", HOT_IDX_6, PART_IDX_7),
            ("减索引：hot 2 索引 / 分区 3 索引", HOT_IDX_2, PART_IDX_3),
        ]:
            build(hi, pi)
            nh = int(psql("SELECT count(*) FROM pg_index WHERE indrelid='public.session_bodies_hot'::regclass;").splitlines()[-1])
            np_ = int(psql("SELECT count(*) FROM pg_index WHERE indrelid='public.session_bodies'::regclass;").splitlines()[-1])
            w_ins, w_pro, rw, rw_b = measure()
            print("\n===== %s =====" % label)
            print("索引数：hot %d / 分区表 %d；逻辑行宽 %s" % (nh, np_, rw))
            print("① 批量 INSERT %d 行   WAL = %10d B ⇒ %7.0f B/行" % (N, w_ins, w_ins / N))
            print("② promote 搬 %d 行    WAL = %10d B ⇒ %7.0f B/行" % (N, w_pro, w_pro / N))
            print("   ⇒ ★★ 每行 WAL / 逻辑行宽 = %.2f  ⇒ ★ WAL ≈ 逻辑行宽 × ~1.1" % (w_ins / N / max(rw_b, 1)))
            out[label] = (nh, np_, w_ins / N, w_pro / N, rw_b)
    finally:
        # ★★★ 回收（R99 轮 · §19.20.65）：守卫形态 + 字面留在 finally 块里
        #   ★★ 【为什么不在这里抽成 helper】——判据判的是「兜底**载体**里是否真的
        #     包着回收动作」⇒ 把 DROP 抽走 ⇒ 载体就【不覆盖】回收 ⇒ 会被判不合格。
        #     ⇒ 所以这里【必须】字面写 DROP DATABASE（另一处同形态的清理由
        #     _drop_db() 负责 ⇒ 两处是同一形态，改一处必须改另一处）。
        #   ★★ SET 与 DROP 必须【逐条发送】⇒ ⇒ 走 stdin=True（★ **裸 stdin 交互模式**，
        #     **不是**脚本模式 —— R102 轮订正；三种 stdin 读入方式的失败语义一致）
        #     ⇒ 一条 `-c` 里把两条并进去 ⇒ 一个隐式事务 ⇒ PG 直接拒绝 ⇒ 清理静默失败。
        #     ⇒ ★★ 但「同一 psql 进程的**多条独立 `-c`**」是**合法**的（各自独立事务、
        #       SET 对后续生效）⇒ ⇒ 「逐条发送」的准确含义是【**不把两条并进同一条 `-c`**】
        #       而**不是**【必须换形态】⇒ ★ 段八 的 shell 腿正是这个形态。
        #   ★★ 超时 120s：实测「terminate 之后 DROP 仍要等被 SIGTERM 的后端收尾」
        #     可达数十秒 ⇒ 15s 会把合法清理砍成失败 ⇒ 失败＝泄漏。
        try:
            psql("SELECT pg_terminate_backend(pid) FROM pg_stat_activity WHERE datname = '%s';" % DB, db="postgres", check=False)
            psql("SET statement_timeout='120s'; DROP DATABASE IF EXISTS %s WITH (FORCE);" % DB, db="postgres", stdin=True, check=False)
            # ★ 查落点：「清理是否真的成功」只能由「库里还有没有」来判
            #   （★ R102 轮订正：本函数走 stdin 形态 ⇒ check=False ⇒ **调用侧也收不到退出码**
            #    ⇒ ⇒ 这里查落点是【唯一】的失败可见性来源 ⇒ 不可省）
            left = psql("SELECT 'LEFT=' || count(*) FROM pg_database WHERE datname = '%s';" % DB, db="postgres", check=False).strip()
            if left != "LEFT=0":
                print("[cleanup] ⚠ 回收未完成：%s" % left)
            print("\n[cleanup] DROP %s" % DB)
        except Exception as e:  # noqa: BLE001 —— 回收失败不得盖掉真正的错误
            print("[cleanup] WARN: %s" % e)

    ks = list(out.keys())
    a, b = out[ks[0]], out[ks[1]]
    print("\n=== 汇总：索引数对每行 WAL 的影响 ===")
    print("  每行 INSERT WAL：%.0f B（%d 索引） ⇒ %.0f B（%d 索引） ⇒ **降 %.1f%%**" % (
        a[2], a[0], b[2], b[0], 100.0 * (a[2] - b[2]) / a[2]))
    print("  每行 promote WAL：%.0f B（%d 索引） ⇒ %.0f B（%d 索引） ⇒ **降 %.1f%%**" % (
        a[3], a[1], b[3], b[1], 100.0 * (a[3] - b[3]) / a[3]))
    print("  ⇒ ★ 结论：减索引几乎不省 WAL ⇒ ★ 杠杆在【把行变瘦】")


if __name__ == "__main__":
    _install_signal_handlers()
    try:
        main()
    except _Terminated as e:
        # ★ 信号路径：异常已沿栈展开 ⇒ finally 块【真的】跑过（库已回收）
        #   ⇒ 这里只把退出码还原成「被信号终止」的形状（128+15）。
        print("⚠ %s ⇒ finally 块的清理已执行" % e, file=sys.stderr)
        sys.exit(143)
