# ★★★ 真正不可压缩：每一段的输入都不同（g + i + random）
INCOMPRESSIBLE = "(SELECT string_agg(md5(g::text || i::text || random()::text), '') FROM generate_series(1, 344) i)"

DDL_TMPL = r"""
CREATE TABLE public.session_bodies_hot (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    session_id text NOT NULL, turn_no integer NOT NULL, tenant_id varchar(255) NOT NULL,
    request_id text NOT NULL, request_delta jsonb, response_delta jsonb, outbound_body jsonb,
    request_attachments jsonb DEFAULT '[]'::jsonb, response_attachments jsonb DEFAULT '[]'::jsonb,
    ts timestamptz DEFAULT now() NOT NULL, partition_date date DEFAULT CURRENT_DATE NOT NULL,
    kind text DEFAULT 'turn_delta'::text NOT NULL
) WITH (fillfactor='90');
ALTER TABLE ONLY public.session_bodies_hot ALTER COLUMN request_delta SET COMPRESSION lz4;
ALTER TABLE ONLY public.session_bodies_hot ALTER COLUMN response_delta SET COMPRESSION lz4;
ALTER TABLE ONLY public.session_bodies_hot ALTER COLUMN outbound_body SET COMPRESSION lz4;
ALTER TABLE ONLY public.session_bodies_hot ADD CONSTRAINT session_bodies_hot_pkey PRIMARY KEY (id, partition_date);
--HOTIDX--
CREATE TABLE public.session_bodies (
    id bigint NOT NULL, session_id text NOT NULL, turn_no integer NOT NULL, tenant_id varchar(255) NOT NULL,
    request_id text NOT NULL, request_delta jsonb, response_delta jsonb, outbound_body jsonb,
    request_attachments jsonb DEFAULT '[]'::jsonb, response_attachments jsonb DEFAULT '[]'::jsonb,
    ts timestamptz DEFAULT now() NOT NULL, partition_date date DEFAULT CURRENT_DATE NOT NULL,
    kind text DEFAULT 'turn_delta'::text NOT NULL
);
ALTER TABLE ONLY public.session_bodies ALTER COLUMN request_delta SET COMPRESSION lz4;
ALTER TABLE ONLY public.session_bodies ALTER COLUMN response_delta SET COMPRESSION lz4;
ALTER TABLE ONLY public.session_bodies ALTER COLUMN outbound_body SET COMPRESSION lz4;
ALTER TABLE ONLY public.session_bodies ADD CONSTRAINT session_bodies_pkey PRIMARY KEY (id, partition_date);
--PARTIDX--
CREATE OR REPLACE FUNCTION public.promote_session_bodies_hot_to_partition(
    retention_window interval DEFAULT '8 hours', batch_size integer DEFAULT 5000
) RETURNS TABLE(moved_count bigint) AS $$
DECLARE cutoff_ts timestamptz;
BEGIN
    cutoff_ts := now() - retention_window;
    PERFORM pg_advisory_xact_lock(hashtext('session_bodies_hot_promote'));
    WITH to_move AS (
        SELECT id, session_id, turn_no, tenant_id, request_id, ts,
               request_delta, response_delta, outbound_body,
               request_attachments, response_attachments, partition_date
        FROM public.session_bodies_hot
        WHERE ts < cutoff_ts ORDER BY ts LIMIT batch_size FOR UPDATE SKIP LOCKED
    ), inserted AS (
        INSERT INTO public.session_bodies (
            id, session_id, turn_no, tenant_id, request_id, ts,
            request_delta, response_delta, outbound_body,
            request_attachments, response_attachments, partition_date
        )
        SELECT id, session_id, turn_no, tenant_id, request_id, ts,
               request_delta, response_delta, outbound_body,
               request_attachments, response_attachments, partition_date
        FROM to_move ON CONFLICT (id, partition_date) DO NOTHING RETURNING id
    ), deleted AS (
        DELETE FROM public.session_bodies_hot WHERE id IN (SELECT id FROM inserted) RETURNING 1
    )
    SELECT count(*) INTO moved_count FROM deleted;
    RETURN QUERY SELECT moved_count;
END;
$$ LANGUAGE plpgsql;
"""

