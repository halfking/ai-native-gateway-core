#!/usr/bin/env python3
"""§143.51 本地真库实验：promote / INSERT 的每行 WAL 成本，与【行宽】【索引数】的关系。

★ 为什么要本地实验（而不是在生产上测）：
  生产上要确证「promote 的 WAL 成本构成」需跑 `EXPLAIN (ANALYZE, WAL)` 或真实 promote
  ⇒ ⇒ **那是写操作 ⇒ 需属主授权** ⇒ ⇒ 本实验在**本地真库**（PG 17.10，与生产同版本）
  用**受控实验**把它测出来 ⇒ **零生产写入、零残留**（一次性库，结束 DROP）。

★★★ 前两版的实验设计缺陷（同一族，值得记住）：
  第一版灌 `repeat('x', 11000)` ⇒ lz4 压到几乎为 0 ⇒ 每行 WAL 测出 1.9 kB（假的）
  第二版灌 `repeat(md5(random()::text), 344)` ⇒ ★ **仍是同一串重复 344 次**
          ⇒ lz4 照样压到 136 B ⇒ 还是假的
  ⇒⇒ 第三版：**每一段都不同** ⇒ `md5(g::text || i::text || random()::text)` 拼 344 次
          ⇒ 真正不可压缩 ⇒ 行宽可标定
  ⇒⇒ ★★ **通用式：★ 压测数据的【可压缩性】会系统性改变 WAL 读数**
     ⇒ ⇒ 「随机」不等于「不可压缩」⇒ ⇒ **必须用【每段都不同】的内容**。

★ 本实验的三条结论（252 生产读数的对照见 runbook §143.51）：
  ① promote 的 WAL 与批量 N **严格线性 ⇒ 每次调用几乎没有固定开销**
     ⇒ ⇒ **推翻了 §143.50 的「每次调用 ≈5,043 kB 固定开销」**（那是用推算行宽相减得来的）
  ② **逐行 INSERT 与批量 INSERT 的 WAL 相同（1.0 倍）**
     ⇒ ⇒ 「逐行写更贵」不成立
  ③ **索引数从 6→2 / 7→3，每行 WAL 只降 1%**
     ⇒ ⇒ **减索引不是杠杆；★ 行的大小才是** ⇒ ⇒ ⇒ 每行 WAL ≈ 逻辑行宽 × 1.1

★ 用法（本地）：python3 scripts/audit/verify_promote_wal_cost_local.py
"""
import subprocess
import sys

DB = "itgate_14351"
N = 2000

# ★★★ 真正不可压缩：每一段的输入都不同（g + i + random）
INCOMPRESSIBLE = "(SELECT string_agg(md5(g::text || i::text || random()::text), '') FROM generate_series(1, 344) i)"

DDL_TMPL = r"""
CREATE TABLE public.session_bodies_hot (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    session_id text NOT NULL, turn_no integer NOT NULL, tenant_id varchar(255) NOT NULL,
    request_id text NOT NULL, request_delta jsonb, response_delta jsonb, outbound_body jsonb,
    request_attachments jsonb DEFAULT '[]'::jsonb, response_attachments jsonb DEFAULT '[]'::jsonb,
    ts timestamptz DEFAULT now() NOT NULL, partition_date date DEFAULT CURRENT_DATE NOT NULL,
    kind text DEFAULT 'turn_delta'::text NOT NULL
) WITH (fillfactor='90');
ALTER TABLE ONLY public.session_bodies_hot ALTER COLUMN request_delta SET COMPRESSION lz4;
ALTER TABLE ONLY public.session_bodies_hot ALTER COLUMN response_delta SET COMPRESSION lz4;
ALTER TABLE ONLY public.session_bodies_hot ALTER COLUMN outbound_body SET COMPRESSION lz4;
ALTER TABLE ONLY public.session_bodies_hot ADD CONSTRAINT session_bodies_hot_pkey PRIMARY KEY (id, partition_date);
--HOTIDX--
CREATE TABLE public.session_bodies (
    id bigint NOT NULL, session_id text NOT NULL, turn_no integer NOT NULL, tenant_id varchar(255) NOT NULL,
    request_id text NOT NULL, request_delta jsonb, response_delta jsonb, outbound_body jsonb,
    request_attachments jsonb DEFAULT '[]'::jsonb, response_attachments jsonb DEFAULT '[]'::jsonb,
    ts timestamptz DEFAULT now() NOT NULL, partition_date date DEFAULT CURRENT_DATE NOT NULL,
    kind text DEFAULT 'turn_delta'::text NOT NULL
);
ALTER TABLE ONLY public.session_bodies ALTER COLUMN request_delta SET COMPRESSION lz4;
ALTER TABLE ONLY public.session_bodies ALTER COLUMN response_delta SET COMPRESSION lz4;
ALTER TABLE ONLY public.session_bodies ALTER COLUMN outbound_body SET COMPRESSION lz4;
ALTER TABLE ONLY public.session_bodies ADD CONSTRAINT session_bodies_pkey PRIMARY KEY (id, partition_date);
--PARTIDX--
CREATE OR REPLACE FUNCTION public.promote_session_bodies_hot_to_partition(
    retention_window interval DEFAULT '8 hours', batch_size integer DEFAULT 5000
) RETURNS TABLE(moved_count bigint) AS $$
DECLARE cutoff_ts timestamptz;
BEGIN
    cutoff_ts := now() - retention_window;
    PERFORM pg_advisory_xact_lock(hashtext('session_bodies_hot_promote'));
    WITH to_move AS (
        SELECT id, session_id, turn_no, tenant_id, request_id, ts,
               request_delta, response_delta, outbound_body,
               request_attachments, response_attachments, partition_date
        FROM public.session_bodies_hot
        WHERE ts < cutoff_ts ORDER BY ts LIMIT batch_size FOR UPDATE SKIP LOCKED
    ), inserted AS (
        INSERT INTO public.session_bodies (
            id, session_id, turn_no, tenant_id, request_id, ts,
            request_delta, response_delta, outbound_body,
            request_attachments, response_attachments, partition_date
        )
        SELECT id, session_id, turn_no, tenant_id, request_id, ts,
               request_delta, response_delta, outbound_body,
               request_attachments, response_attachments, partition_date
        FROM to_move ON CONFLICT (id, partition_date) DO NOTHING RETURNING id
    ), deleted AS (
        DELETE FROM public.session_bodies_hot WHERE id IN (SELECT id FROM inserted) RETURNING 1
    )
    SELECT count(*) INTO moved_count FROM deleted;
    RETURN QUERY SELECT moved_count;
END;
$$ LANGUAGE plpgsql;
"""

HOT_IDX_6 = """
ALTER TABLE ONLY public.session_bodies_hot ADD CONSTRAINT session_bodies_hot_unique UNIQUE (session_id, turn_no, tenant_id, partition_date);
ALTER TABLE ONLY public.session_bodies_hot ADD CONSTRAINT session_bodies_with_current_month UNIQUE (tenant_id, request_id, partition_date);
CREATE INDEX idx_session_bodies_hot_request ON public.session_bodies_hot USING btree (request_id, tenant_id);
CREATE INDEX idx_session_bodies_hot_tenant_session_turn_request ON public.session_bodies_hot USING btree (tenant_id, session_id, turn_no, request_id);
CREATE UNIQUE INDEX uq_session_bodies_hot_final_full ON public.session_bodies_hot USING btree (tenant_id, session_id, partition_date) WHERE (kind = 'final_full'::text);
"""
HOT_IDX_2 = "CREATE INDEX idx_session_bodies_hot_request ON public.session_bodies_hot USING btree (request_id, tenant_id);"

PART_IDX_7 = """
ALTER TABLE ONLY public.session_bodies ADD CONSTRAINT session_bodies_tenant_request_partition_key UNIQUE (tenant_id, request_id, partition_date);
ALTER TABLE ONLY public.session_bodies ADD CONSTRAINT session_bodies_tenant_session_turn_partition_key UNIQUE (tenant_id, session_id, turn_no, partition_date);
CREATE INDEX idx_session_bodies_request ON public.session_bodies USING btree (request_id, tenant_id);
CREATE INDEX idx_session_bodies_session ON public.session_bodies USING btree (session_id, turn_no);
CREATE INDEX idx_session_bodies_tenant_session_turn_request ON public.session_bodies USING btree (tenant_id, session_id, turn_no, request_id);
CREATE UNIQUE INDEX uq_session_bodies_final_full ON public.session_bodies USING btree (tenant_id, session_id, partition_date) WHERE (kind = 'final_full'::text);
"""
PART_IDX_3 = """
CREATE INDEX idx_session_bodies_request ON public.session_bodies USING btree (request_id, tenant_id);
CREATE INDEX idx_session_bodies_session ON public.session_bodies USING btree (session_id, turn_no);
"""

FILL = r"""
INSERT INTO public.session_bodies_hot
  (session_id, turn_no, tenant_id, request_id, ts, partition_date,
   request_delta, response_delta, outbound_body)
SELECT 'sess_'||g, 1, 'tenant_'||(g%%7), 'req_'||g,
       now() - interval '2 hours', CURRENT_DATE,
       jsonb_build_array(jsonb_build_object('role','user','content', %s)),
       jsonb_build_array(jsonb_build_object('role','assistant','content', %s)),
       jsonb_build_array(jsonb_build_object('role','assistant','content', %s))
FROM generate_series(1, %d) g;
"""


def psql(sql, db=DB, stdin=False):
    cmd = ["docker", "exec", "-i", "llm-gateway-pg", "psql", "-U", "llm_gateway", "-d", db,
           "-v", "ON_ERROR_STOP=1", "-P", "pager=off", "-t", "-A", "-F", "|"]
    r = subprocess.run(cmd, input=sql, capture_output=True, text=True) if stdin \
        else subprocess.run(cmd + ["-c", sql], capture_output=True, text=True)
    if r.returncode != 0:
        print("SQL FAILED rc=%d\n%s\n%s" % (r.returncode, sql[:300], r.stderr[:1000]))
        raise SystemExit(1)
    return r.stdout.strip()


def wal():
    return int(psql("SELECT wal_bytes FROM pg_stat_wal;").splitlines()[-1])


def build(hot_idx, part_idx):
    psql("DROP DATABASE IF EXISTS %s;" % DB, db="postgres")
    psql("CREATE DATABASE %s;" % DB, db="postgres")
    psql("SET statement_timeout='300s';\n"
         + DDL_TMPL.replace("--HOTIDX--", hot_idx).replace("--PARTIDX--", part_idx), stdin=True)


def fill():
    psql(FILL % (INCOMPRESSIBLE, INCOMPRESSIBLE, INCOMPRESSIBLE, N))


def measure():
    """⇒ (批量 INSERT 的 WAL, promote 的 WAL, 逻辑行宽)"""
    psql("TRUNCATE public.session_bodies_hot; TRUNCATE public.session_bodies;")
    fill()
    rw_b = int(psql("SELECT avg(pg_column_size(t))::bigint FROM public.session_bodies_hot t LIMIT 200;").splitlines()[-1])
    rw = psql("SELECT pg_size_pretty(%d::bigint);" % rw_b)
    # ★ 清场后重灌 ⇒ 测「灌这一批」的 WAL（TRUNCATE 在基线之前，不计入）
    psql("TRUNCATE public.session_bodies_hot; TRUNCATE public.session_bodies;")
    b = wal()
    fill()
    w_ins = wal() - b
    # ★ 复用刚灌的行 ⇒ 测 promote 的 WAL
    b2 = wal()
    psql("SELECT moved_count FROM public.promote_session_bodies_hot_to_partition('1 hour'::interval, 5000);")
    w_pro = wal() - b2
    return w_ins, w_pro, rw, rw_b


def main():
    out = {}
    try:
        for label, hi, pi in [
            ("生产形态：hot 6 索引 / 分区 7 索引", HOT_IDX_6, PART_IDX_7),
            ("减索引：hot 2 索引 / 分区 3 索引", HOT_IDX_2, PART_IDX_3),
        ]:
            build(hi, pi)
            nh = int(psql("SELECT count(*) FROM pg_index WHERE indrelid='public.session_bodies_hot'::regclass;").splitlines()[-1])
            np_ = int(psql("SELECT count(*) FROM pg_index WHERE indrelid='public.session_bodies'::regclass;").splitlines()[-1])
            w_ins, w_pro, rw, rw_b = measure()
            print("\n===== %s =====" % label)
            print("索引数：hot %d / 分区表 %d；逻辑行宽 %s" % (nh, np_, rw))
            print("① 批量 INSERT %d 行   WAL = %10d B ⇒ %7.0f B/行" % (N, w_ins, w_ins / N))
            print("② promote 搬 %d 行    WAL = %10d B ⇒ %7.0f B/行" % (N, w_pro, w_pro / N))
            print("   ⇒ ★★ 每行 WAL / 逻辑行宽 = %.2f  ⇒ ★ WAL ≈ 逻辑行宽 × ~1.1" % (w_ins / N / max(rw_b, 1)))
            out[label] = (nh, np_, w_ins / N, w_pro / N, rw_b)
    finally:
        psql("DROP DATABASE IF EXISTS %s;" % DB, db="postgres")
        print("\n[cleanup] DROP %s" % DB)

    ks = list(out.keys())
    a, b = out[ks[0]], out[ks[1]]
    print("\n=== 汇总：索引数对每行 WAL 的影响 ===")
    print("  每行 INSERT WAL：%.0f B（%d 索引） ⇒ %.0f B（%d 索引） ⇒ **降 %.1f%%**" % (
        a[2], a[0], b[2], b[0], 100.0 * (a[2] - b[2]) / a[2]))
    print("  每行 promote WAL：%.0f B（%d 索引） ⇒ %.0f B（%d 索引） ⇒ **降 %.1f%%**" % (
        a[3], a[1], b[3], b[1], 100.0 * (a[3] - b[3]) / a[3]))
    print("  ⇒ ★ 结论：减索引几乎不省 WAL ⇒ ★ 杠杆在【把行变瘦】")


if __name__ == "__main__":
    main()
