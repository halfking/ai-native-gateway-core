#!/usr/bin/env python3
"""§143.51 本地真库实验：promote / INSERT 的每行 WAL 成本，与【行宽】【索引数】的关系。

★ 为什么要本地实验（而不是在生产上测）：
  生产上要确证「promote 的 WAL 成本构成」需跑 `EXPLAIN (ANALYZE, WAL)` 或真实 promote
  ⇒ ⇒ **那是写操作 ⇒ 需属主授权** ⇒ ⇒ 本实验在**本地真库**（PG 17.10，与生产同版本）
  用**受控实验**把它测出来 ⇒ **零生产写入、零残留**（一次性库，结束 DROP）。

★★★ 前两版的实验设计缺陷（同一族，值得记住）：
  第一版灌 `repeat('x', 11000)` ⇒ lz4 压到几乎为 0 ⇒ 每行 WAL 测出 1.9 kB（假的）
  第二版灌 `repeat(md5(random()::text), 344)` ⇒ ★ **仍是同一串重复 344 次**
          ⇒ lz4 照样压到 136 B ⇒ 还是假的
  ⇒⇒ 第三版：**每一段都不同** ⇒ `md5(g::text || i::text || random()::text)` 拼 344 次
          ⇒ 真正不可压缩 ⇒ 行宽可标定
  ⇒⇒ ★★ **通用式：★ 压测数据的【可压缩性】会系统性改变 WAL 读数**
     ⇒ ⇒ 「随机」不等于「不可压缩」⇒ ⇒ **必须用【每段都不同】的内容**。

★ 本实验的三条结论（252 生产读数的对照见 runbook §143.51）：
  ① promote 的 WAL 与批量 N **严格线性 ⇒ 每次调用几乎没有固定开销**
     ⇒ ⇒ **推翻了 §143.50 的「每次调用 ≈5,043 kB 固定开销」**（那是用推算行宽相减得来的）
  ② **逐行 INSERT 与批量 INSERT 的 WAL 相同（1.0 倍）**
     ⇒ ⇒ 「逐行写更贵」不成立
  ③ **索引数从 6→2 / 7→3，每行 WAL 只降 1%**
     ⇒ ⇒ **减索引不是杠杆；★ 行的大小才是** ⇒ ⇒ ⇒ 每行 WAL ≈ 逻辑行宽 × 1.1

★ 用法（本地）：python3 scripts/audit/verify_promote_wal_cost_local.py
"""
