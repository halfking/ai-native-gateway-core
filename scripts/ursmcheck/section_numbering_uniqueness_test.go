//
//	① `## §230 · R103-20261022 ★★★ …`      （节号在最前）   ⇒ 73 条
//	② `## 2026-10-19 §105 轮：三次量具事故…`  （★ 日期在前、节号在后）⇒ 42 条
//
// ⇒ ⇒ 原版【漏了 42 行（36%）】⇒ ⇒ ★★ **那 42 个节号同样会撞号，而门护不住**
// ⇒ ⇒ ★★★ **★ 这是「门恒绿」的第三层：搜索面【本身】不完整 ⇒ 门是瞎的**
// ⇒ ⇒ ★★ 「门自检恒绿」的三层清单（本轮合齐）：
// 　　第一层 = 【自指】（判据引用了它要测的那个字面量）
// 　　第二层 = 【标记不唯一】（同一个字面量在别处也有）
// 　　第三层 = ★★ 【搜索面不完整】（判据只覆盖了目标的一部分）
//
// ★ 修法：标题行里取【第一个】`§` 之后的节号 ⇒ 两种形态都覆盖 ⇒
// ★【且仍不误伤正文引用】（正文引用不是标题行，`^\s*#{2,4}\s` 判不到）。
var headingRe = regexp.MustCompile(`^\s*#{2,4}\s.*?§([0-9][0-9.]*[A-Za-z]*)(\s|$)`)

// parseSectionNumbers 返回该文本里全部带节号的标题行及其出现次数。
func parseSectionNumbers(text string) (map[string]int, []string) {
	counts := map[string]int{}
	var order []string
	for _, line := range strings.Split(text, "\n") {
		m := headingRe.FindStringSubmatch(line)
		if m == nil {
			continue
		}
		num := m[1]
		if _, seen := counts[num]; !seen {
			order = append(order, num)
		}
		counts[num]++
	}
	return counts, order
}

// duplicatePairs 返回出现次数 > 1 的节号（按节号排序）。
func duplicatePairs(counts map[string]int) []string {
	var out []string
	for num, c := range counts {
		if c > 1 {
			out = append(out, num)
		}
	}
	sort.Strings(out)
	return out
}

// readSectionCounts 读文件并解析，同时做【搜索面完整性】的双口径互证。
func readSectionCounts(t *testing.T, path string) (map[string]int, []string) {
	t.Helper()
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("读 %s 失败：%v", path, err)
	}
	counts, order := parseSectionNumbers(string(raw))

	// ★ 搜索面完整性自检（★ R63 §2.4 通用式：断言结果非空 ＋ 断言条数与期望一致）
	if len(counts) == 0 {
		t.Fatalf("%s：一个带节号的标题都没解析出来 ⇒ 【搜索面不完整】⇒ 判据不可信", path)
	}
	if len(order) != len(counts) {
		t.Fatalf("%s：唯一节号数 %d != 出现顺序长度 %d ⇒ 解析面不自洽", path, len(counts), len(order))
	}
	// ★★★ 独立第二口径（★ 本轮【修掉了一个真洞】）：
	//
	//   原版：口径 B = 「用**同一个正则**数匹配行数」，口径 A = 「各节号次数之和」
	//     ⇒ ⇒ ★★ 两个数【同源】⇒ ⇒ 【恒真】⇒ ⇒ **它看着像互证，其实是自证**
	//     ⇒ ⇒ ★★ 这正是并行会话 R99 轮通报的「门自检自己会恒绿」的**同源形态**。
	//
	//   现版：口径 B = 【纯字符串判据】—— 行以 '#' 开头 且 含 " §"
	//     ⇒ ⇒ 【完全不解析节号、不用任何正则】⇒ ⇒ 与口径 A 【真正独立】
	//     ⇒ ⇒ ★★ 改坏解析正则 ⇒ 口径 A 的和变少 ⇒ 口径 B 不变 ⇒ 【两数不等 ⇒ 红】
	//     ⇒ ⇒ ★★★ **这才是互证该有的样子：两条口径的失效方式【互不相同】**。
	total := 0
	for _, c := range counts {
		total += c
	}
	// ★ 口径 B：纯字符串判据（★ 故意【不用】headingRe，也不解析节号本体）
	//   ★★ 只判【形态】：「以 # 开头」＋「含 ' §'」＋「§ 之后第一个字符是数字」
	//   ⇒ ⇒ 它与口径 A 的【失效方式不同】：A 解析节号本体（会被「截断字母后缀」
	//   「漏掉一层标题」这类改动弄坏），B 只看形态（不会跟着坏）⇒ ⇒ 两口径互证有效。
	independentLines := 0
	for _, line := range strings.Split(string(raw), "\n") {
		trimmed := strings.TrimSpace(line)
		// ★ 判「是 2~4 级标题」—— ★ 纯字符串判层级（★ 故意【不用】正则），
		//   否则口径 B 就会退化成口径 A 的同源物 ⇒ ⇒ 互证失效。
		hashes := 0
		for hashes < len(trimmed) && trimmed[hashes] == '#' {
			hashes++
		}
		if hashes < 2 || hashes > 4 {
			continue
		}
		if hashes >= len(trimmed) || trimmed[hashes] != ' ' {
			continue
		}
		idx := strings.Index(trimmed, "§")
		if idx < 0 {
			continue
		}
		rest := trimmed[idx+len("§"):]
		if rest == "" || rest[0] < '0' || rest[0] > '9' {
			continue
		}
		// ★★ 判别要点（★ 实测得来）：节号后面必须跟【空白或行尾】⇒
		//   · `## §230 · R103-20261022`     ⇒ 数字后是空格   ⇒ 是节号
		//   · `## 2026-10-19 §105 轮：…`     ⇒ 数字后是空格   ⇒ 是节号
		//   · `## …（… llm-gateway-go R61 §19.7）` ⇒ 数字后是 `）` ⇒ ★ 不是节号（是尾部引用）
		//   · `#### ② …逐字复现 §19.20.35**`        ⇒ 数字后是 `*` ⇒ ★ 不是节号
		// ⇒ ★ 只扫「数字串」不解析节号本体 ⇒ 仍与口径 A 独立。
		j := 0
		for j < len(rest) && (rest[j] == '.' || (rest[j] >= '0' && rest[j] <= '9') ||
			(rest[j] >= 'a' && rest[j] <= 'z') || (rest[j] >= 'A' && rest[j] <= 'Z')) {
			j++
		}
		if j == 0 {
			continue
		}
		if j < len(rest) && rest[j] != ' ' && rest[j] != '\t' {
			continue
		}
		independentLines++
	}
	if independentLines != total {
		t.Fatalf("%s：独立口径数出的标题行数 %d != 解析口径数出的节号次数之和 %d ⇒ "+
			"【搜索面不完整】⇒ ★ 别据此下「无重复」的结论\n"+
			"  ★ 两口径【已刻意做成互不相同】：口径 B 是纯字符串判据（行以 # 开头且含 §）、"+
			"不解析节号、不用解析正则 ⇒ 解析器坏了它不会跟着坏",
			path, independentLines, total)
	}
	return counts, order
}

