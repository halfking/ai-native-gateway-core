// TestDataInitExecute_OnIsolatedDB_ReallyDeletesRows 是本文件的主腿：
// 走**生产同款**的 HTTP 路径（preview → execute），
// 然后逐表断言「行真的没了」「受保护行还在」「审计行写进去了」。
func TestDataInitExecute_OnIsolatedDB_ReallyDeletesRows(t *testing.T) {
	pool := dataInitIsolatedPool(t)

	ctx, cancel := context.WithTimeout(context.Background(), 60*time.Second)
	defer cancel()
	if _, err := pool.Exec(ctx, dataInitFixtureDDL); err != nil {
		t.Fatalf("create fixture schema: %v", err)
	}
	if _, err := pool.Exec(ctx, dataInitFixtureSeed); err != nil {
		t.Fatalf("seed fixture: %v", err)
	}

	h := NewHandler(pool, "", nil, nil)

	// ① preview：拿到令牌与「将要删多少」。
	body, _ := json.Marshal(dataInitPreviewRequest{Categories: dataInitSelectedCategories})
	prevRec := httptest.NewRecorder()
	h.handleDataInitPreview(prevRec, dataInitAuthedRequest(http.MethodPost,
		"/api/admin/data-lifecycle/data-init/preview", string(body)))
	if prevRec.Code != http.StatusOK {
		t.Fatalf("preview: expected 200, got %d: %s", prevRec.Code, prevRec.Body.String())
	}
	var prev dataInitPreviewResponse
	if err := json.Unmarshal(prevRec.Body.Bytes(), &prev); err != nil {
		t.Fatalf("decode preview: %v", err)
	}
	if prev.ConfirmToken == "" {
		t.Fatal("preview must issue a confirm token")
	}
	// 预览口径：受保护行不算进 target_rows。
	if prev.TotalTargetRows != 9 {
		t.Errorf("preview target rows = %d, want 9", prev.TotalTargetRows)
	}

	// ② execute：带上 preview 签发的令牌。
	execBody, _ := json.Marshal(dataInitExecuteRequest{
		Categories:   dataInitSelectedCategories,
		ConfirmToken: prev.ConfirmToken,
	})
	execRec := httptest.NewRecorder()
	h.handleDataInitExecute(execRec, dataInitAuthedRequest(http.MethodPost,
		"/api/admin/data-lifecycle/data-init/execute", string(execBody)))
	if execRec.Code != http.StatusOK {
		t.Fatalf("execute: expected 200, got %d: %s", execRec.Code, execRec.Body.String())
	}
	var resp dataInitExecuteResponse
	if err := json.Unmarshal(execRec.Body.Bytes(), &resp); err != nil {
		t.Fatalf("decode execute: %v", err)
	}

	// ③ 断言「真的删了」——逐类别对拍。
	if resp.TotalRowsDeleted != 9 {
		t.Errorf("total rows deleted = %d, want 9", resp.TotalRowsDeleted)
	}
	got := map[string]int64{}
	for _, r := range resp.Results {
		got[r.Key] = r.RowsDeleted
	}
	for key, want := range dataInitExpectedDeletes {
		if got[key] != want {
			t.Errorf("category %s: rows_deleted = %d, want %d (all=%v)", key, got[key], want, got)
		}
	}

	// ④ 断言**库里真的少了行**（响应不是自说自话）。
	if n := dataInitCount(t, pool, "SELECT count(*) FROM public.users"); n != 1 {
		t.Errorf("users left = %d, want 1 (only the super admin)", n)
	}
	if n := dataInitCount(t, pool, "SELECT count(*) FROM public.api_keys"); n != 1 {
		t.Errorf("api_keys left = %d, want 1 (only the system key)", n)
	}
	if n := dataInitCount(t, pool, "SELECT count(*) FROM public.tenants"); n != 1 {
		t.Errorf("tenants left = %d, want 1 (only default)", n)
	}
	if n := dataInitCount(t, pool, "SELECT count(*) FROM public.session_summaries"); n != 0 {
		t.Errorf("session_summaries left = %d, want 0", n)
	}
	if n := dataInitCount(t, pool, "SELECT count(*) FROM public.credentials"); n != 0 {
		t.Errorf("credentials left = %d, want 0", n)
	}
	if n := dataInitCount(t, pool, "SELECT count(*) FROM public.credential_probe_configs"); n != 0 {
		t.Errorf("credential_probe_configs left = %d, want 0", n)
	}

	// ⑤ 断言受保护行**确实还在**（不是「恰好也没被匹配」）。
	if n := dataInitCount(t, pool, "SELECT count(*) FROM public.users WHERE role = 'super_admin'"); n != 1 {
		t.Errorf("super admins left = %d, want 1", n)
	}
	if n := dataInitCount(t, pool, "SELECT count(*) FROM public.api_keys WHERE is_system = true"); n != 1 {
		t.Errorf("system keys left = %d, want 1", n)
	}
	if n := dataInitCount(t, pool, "SELECT count(*) FROM public.tenants WHERE code = 'default'"); n != 1 {
		t.Errorf("default tenants left = %d, want 1", n)
	}

	// ⑥ 断言审计行写进去了，且内容对得上这次执行。
	if n := dataInitCount(t, pool, "SELECT count(*) FROM public.routing_audit_log"); n != 1 {
		t.Fatalf("audit rows = %d, want 1", n)
	}
	var actor, action, digest string
	var cats string
	if err := pool.QueryRow(ctx,
		`SELECT actor, action, after_json->>'plan_digest', after_json->>'categories'
		   FROM public.routing_audit_log`,
	).Scan(&actor, &action, &digest, &cats); err != nil {
		t.Fatalf("read audit row: %v", err)
	}
	if actor != "root" {
		t.Errorf("audit actor = %q, want %q", actor, "root")
	}
	if action != "data_init_reset" {
		t.Errorf("audit action = %q, want %q", action, "data_init_reset")
	}
	if digest == "" {
		t.Error("audit row must carry the plan digest")
	}
	for _, key := range dataInitSelectedCategories {
		if !strings.Contains(cats, key) {
			t.Errorf("audit categories %q missing %q", cats, key)
		}
	}
}

// TestDataInitExecute_OnIsolatedDB_RollsBackWhenADeleteFails 钉住
// 「审计与删除同事务」：中途失败 ⇒ **前面已经删掉的行全部回滚**，且不留审计行。
//
// ★ 造法：加一张 user_profiles（FK → users(id)，**NO ACTION**）不在删除计划里
//
//	⇒ 删 users 时撞外键 ⇒ 整个事务失败。
func TestDataInitExecute_OnIsolatedDB_RollsBackWhenADeleteFails(t *testing.T) {
	pool := dataInitIsolatedPool(t)

	ctx, cancel := context.WithTimeout(context.Background(), 60*time.Second)
	defer cancel()
	if _, err := pool.Exec(ctx, dataInitFixtureDDL); err != nil {
		t.Fatalf("create fixture schema: %v", err)
	}
	if _, err := pool.Exec(ctx, dataInitFixtureSeed); err != nil {
		t.Fatalf("seed fixture: %v", err)
	}
	// 这张表不在删除计划里 ⇒ 删 users 必然撞外键。
	if _, err := pool.Exec(ctx, `
		CREATE TABLE public.user_profiles (
			id       serial PRIMARY KEY,
			user_id  bigint NOT NULL REFERENCES public.users(id),
			created_at timestamptz NOT NULL DEFAULT now()
		);
		INSERT INTO public.user_profiles (user_id) VALUES (2);
	`); err != nil {
		t.Fatalf("create blocking child table: %v", err)
	}

	h := NewHandler(pool, "", nil, nil)

	body, _ := json.Marshal(dataInitPreviewRequest{Categories: dataInitSelectedCategories})
	prevRec := httptest.NewRecorder()
	h.handleDataInitPreview(prevRec, dataInitAuthedRequest(http.MethodPost,
		"/api/admin/data-lifecycle/data-init/preview", string(body)))
	if prevRec.Code != http.StatusOK {
		t.Fatalf("preview: expected 200, got %d: %s", prevRec.Code, prevRec.Body.String())
	}
	var prev dataInitPreviewResponse
	if err := json.Unmarshal(prevRec.Body.Bytes(), &prev); err != nil {
		t.Fatalf("decode preview: %v", err)
	}

	execBody, _ := json.Marshal(dataInitExecuteRequest{
		Categories:   dataInitSelectedCategories,
		ConfirmToken: prev.ConfirmToken,
	})
	execRec := httptest.NewRecorder()
	h.handleDataInitExecute(execRec, dataInitAuthedRequest(http.MethodPost,
		"/api/admin/data-lifecycle/data-init/execute", string(execBody)))
	if execRec.Code != http.StatusInternalServerError {
		t.Fatalf("execute: expected 500 on a mid-plan failure, got %d: %s", execRec.Code, execRec.Body.String())
	}

	// ★ 前面那些类别（request_records / credentials / api_keys）**必须还在**——
	//   它们排在 users 之前，已经被 DELETE 过 ⇒ 只有回滚才能让它们回来。
	for table, want := range map[string]int64{
		"users":                    3,
		"api_keys":                 2,
		"tenants":                  2,
		"session_summaries":        2,
		"credentials":              1,
		"credential_probe_configs": 2,
	} {
		if n := dataInitCount(t, pool, "SELECT count(*) FROM public."+table); n != want {
			t.Errorf("%s left = %d, want %d (the transaction must have rolled back)", table, n, want)
		}
	}
	// 审计行与删除同事务 ⇒ 失败时**不留痕**（否则就是「没删却留了痕」）。
	if n := dataInitCount(t, pool, "SELECT count(*) FROM public.routing_audit_log"); n != 0 {
		t.Errorf("audit rows = %d, want 0 (the audit row must share the rolled-back transaction)", n)
	}
}

// TestDataInitExecute_OnIsolatedDB_WrongOrderHitsForeignKey 钉住
// 「外键安全的删除顺序」不是注释里的一句承诺，而是**真的会被外键挡住**。
//
// ★ A/B 对照（同一个隔离库）：
//
//	① 交换顺序（credentials 排在 credential_probe_configs 之前）⇒ 必须失败；
//	② 生产顺序 ⇒ 必须成功。
//	⇒ 顺序错了会撞 NO ACTION 外键 ⇒ 注册表里的顺序是**承重**的。
func TestDataInitExecute_OnIsolatedDB_WrongOrderHitsForeignKey(t *testing.T) {
	pool := dataInitIsolatedPool(t)

	ctx, cancel := context.WithTimeout(context.Background(), 60*time.Second)
	defer cancel()
	if _, err := pool.Exec(ctx, dataInitFixtureDDL); err != nil {
		t.Fatalf("create fixture schema: %v", err)
	}
	if _, err := pool.Exec(ctx, dataInitFixtureSeed); err != nil {
		t.Fatalf("seed fixture: %v", err)
	}

	store := newPGDataInitStore(pool)
	actor := dataInitActorRoot()

	// ① 交换顺序 ⇒ 撞外键（NO ACTION）。
	//
	// ★ 顺序不能反：先跑「正确顺序」会把子表/父表都删光，
	//   后跑「错误顺序」就**没有行可删** ⇒ 撞不到外键 ⇒ 断言变成假绿。
	bad, err := buildDataInitPlan([]string{"credentials"}, actor)
	if err != nil {
		t.Fatalf("build plan: %v", err)
	}
	childIdx, parentIdx := -1, -1
	for i, d := range bad.Deletes {
		switch d.Table {
		case "credential_probe_configs":
			childIdx = i
		case "credentials":
			parentIdx = i
		}
	}
	if childIdx < 0 || parentIdx < 0 {
		t.Fatalf("fixture plan missing credential tables: child=%d parent=%d", childIdx, parentIdx)
	}
	bad.Deletes[childIdx], bad.Deletes[parentIdx] = bad.Deletes[parentIdx], bad.Deletes[childIdx]

	_, err = store.Apply(ctx, bad, actor.Username, "data_init_reset", map[string]any{})
	if err == nil {
		t.Fatal("expected the wrong delete order to hit the foreign key")
	}
	msg := err.Error()
	if !strings.Contains(msg, "foreign key") && !strings.Contains(msg, "23503") {
		t.Errorf("expected a foreign-key violation, got: %v", err)
	}

	// ② 生产顺序 ⇒ 成功（子表先于父表）⇒ 同一个隔离库上的 A/B 对照。
	good, err := buildDataInitPlan([]string{"credentials"}, actor)
	if err != nil {
		t.Fatalf("build plan: %v", err)
	}
	if _, err := store.Apply(ctx, good, actor.Username, "data_init_reset", map[string]any{}); err != nil {
		t.Fatalf("production order must succeed, got: %v", err)
	}
	if n := dataInitCount(t, pool, "SELECT count(*) FROM public.credentials"); n != 0 {
		t.Errorf("credentials left = %d, want 0", n)
	}
	if n := dataInitCount(t, pool, "SELECT count(*) FROM public.credential_probe_configs"); n != 0 {
		t.Errorf("credential_probe_configs left = %d, want 0", n)
	}
}
