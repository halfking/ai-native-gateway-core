// dataInitCanCreateDB 预检当前角色能不能建库。
//
// ★ 不能 ⇒ t.Skip 而不是 t.Fatal：
//
//	「环境没有这个权限」是**环境**的陈述，不是被测代码的缺陷。
func dataInitCanCreateDB(t *testing.T, dsn string) bool {
	t.Helper()
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	pool, err := pgxpool.New(ctx, dsn)
	if err != nil {
		t.Logf("连不上 base DSN：%v", err)
		return false
	}
	defer pool.Close()
	var can bool
	if err := pool.QueryRow(ctx,
		"select rolcreatedb or rolsuper from pg_roles where rolname = current_user",
	).Scan(&can); err != nil {
		t.Logf("查角色权限失败：%v", err)
		return false
	}
	return can
}

// dataInitIsolatedPool 造一个一次性库并连上它。
func dataInitIsolatedPool(t *testing.T) *pgxpool.Pool {
	t.Helper()
	base := dataInitTestDSN(t)
	if !dataInitCanCreateDB(t, base) {
		t.Skip("当前角色没有 CREATEDB ⇒ 建不出一次性隔离库 ⇒ 本腿不执行（跳过不构成证据）")
	}
	iso := testdb.Create(t, base)
	pool, err := pgxpool.New(context.Background(), iso)
	if err != nil {
		t.Fatalf("connect to isolated db: %v", err)
	}
	t.Cleanup(pool.Close)
	return pool
}

// dataInitCount 数一行。
func dataInitCount(t *testing.T, pool *pgxpool.Pool, sql string, args ...any) int64 {
	t.Helper()
	var n int64
	if err := pool.QueryRow(context.Background(), sql, args...).Scan(&n); err != nil {
		t.Fatalf("count failed (%s): %v", sql, err)
	}
	return n
}

// dataInitAuthedRequest 造一个带操作者身份的请求。
func dataInitAuthedRequest(method, path, body string) *http.Request {
	var r *http.Request
	if body == "" {
		r = httptest.NewRequest(method, path, nil)
	} else {
		r = httptest.NewRequest(method, path, strings.NewReader(body))
	}
	r = SetAuthContext(r, &AuthContext{
		UserID:   1,
		Username: "root",
		TenantID: "default",
		Role:     "super_admin",
		IsJWT:    true,
	})
	return r
}

