package admin

// 数据初始化（data-init）的**真删除**验证 —— 在一次性隔离库里跑。
//
// # ★ 这条腿补的是哪块缺口
//
// 既有两条真库腿只证明了「不该删的没删」：
//
//   · admin/data_lifecycle_data_init_realdb_test.go      —— 统计口径 + 每条 DELETE 的 EXPLAIN 计划（**不执行任何一行**）
//   · admin/data_lifecycle_data_init_http_realdb_test.go —— HTTP 层的拒绝路径（缺令牌 / 跨类别 / 篡改）
//
// ⇒⇒ **没有任何一条腿证明过「execute 真的删掉了行」**。
// 而 http_realdb_test.go 的文件头写着「真删除只发生在隔离库里」——
// **那句话描述的隔离库当时并不存在** ⇒ 注释承诺的证据是空的。
//
// # ★ 为什么只能在一次性隔离库里做
//
// pgDataInitStore.Apply 在**自己的事务**里 Begin → 删 → Commit ⇒
// 「调完 Apply 再手工回滚」**无效**（Apply 自己提交了）。
// ⇒ 只剩两条路：① 改生产实现加测试钩子（污染生产代码）② 用一次性库。
// ⇒ 选 ②：internal/testdb.Create 自建自销 ⇒ **生产实现一行不改**。
//
// # ★ 隔离边界（写动作不会落到事实源指的库上）
//
// internal/testdb.Create 从 base DSN **派生**一个空库并返回它的 DSN，
// 且自己断言「返回的 DSN 真的落在那个库里」（mustLandInScratch）。
// ⇒ 本文件的所有 INSERT/DELETE 都只打在一次性库上；
//   base DSN（可能指着产品库）只是「建库的落点」，不承载任何一行数据。
//
// # ★ 夹具照生产真源建（211 真库 pg_constraint 实测，2026-11-16）
//
//	· session_summaries → tenants(code) **ON DELETE CASCADE**（生产实测同名约束）
//	· credential_probe_configs → credentials(id) **无 ON DELETE**（生产实测 ⇒ NO ACTION）
//	· users / api_keys **没有**指向 tenants 的外键（生产实测）⇒ 夹具也不加
//
// ⇒ 「计划顺序错了会撞外键」这件事在夹具里是**真的**，不是模拟出来的。
//
// # 环境变量
//
// TEST_DATA_INIT_DSN → LLM_GATEWAY_DATABASE_URL → DATABASE_URL；
// 都没设 ⇒ t.Skip。角色没有 CREATEDB ⇒ t.Skip（跳过不构成证据）。

