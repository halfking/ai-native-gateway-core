	mux.HandleFunc("/api/admin/session-analytics/v2/model-ranking", admin(h.handleSessionRequestRankingV2))
	mux.HandleFunc("/api/admin/session-analytics/v2/provider-ranking", admin(h.handleSessionRequestRankingV2))
