function formatValue(v, indent) {
  if (typeof v === 'string') {
    const q = v.includes("'") && !v.includes('"') ? '"' : "'"
    const escaped = v.replace(/'/g, "\\'")
    return q === "'" ? `'${escaped}'` : `"${v.replace(/"/g, '\\"')}"`
  }
  if (typeof v === 'object' && v !== null) {
    const inner = Object.entries(v)
      .map(([k, val]) => `${' '.repeat(indent + 2)}${k}: ${formatValue(val, indent + 2)},`)
      .join('\n')
    return `{\n${inner}\n${' '.repeat(indent)}}`
  }
  return String(v)
}

function formatBlock(name, obj, indent = 2) {
  const pad = ' '.repeat(indent)
  const lines = Object.entries(obj).map(
    ([k, v]) => `${pad}  ${k}: ${formatValue(v, indent + 2)},`,
  )
  return `${pad}${name}: {\n${lines.join('\n')}\n${pad}},`
}

for (const [locale, blocks] of Object.entries(blocksByLocale)) {
  const approvalPath = path.join(localesDir, locale, 'approval.ts')
  let content = fs.readFileSync(approvalPath, 'utf8')
  if (content.includes('approverManager:')) {
    console.log(`skip ${locale}/approval.ts (already patched)`)
  } else {
    const insert = `\n${formatBlock('approverManager', blocks.approverManager)}\n${formatBlock('notificationChannels', blocks.notificationChannels)}\n${formatBlock('rulesEditor', blocks.rulesEditor)}\n`
    content = content.replace(/\n}\s*$/, `${insert}}`)
    // Ensure config block has trailing comma before new top-level keys
    content = content.replace(/(\n  \})\n  approverManager:/, '$1,\n  approverManager:')
    fs.writeFileSync(approvalPath, content)
    console.log(`patched ${locale}/approval.ts`)
  }
}

