CREATE TABLE public.session_tools (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    execution_id VARCHAR(64) NOT NULL,
    session_id VARCHAR(64) NOT NULL,
    request_id VARCHAR(64) NOT NULL,
    tenant_id VARCHAR(64) NOT NULL,
    turn_no INT,                     -- 134 无；S1a 补（hook 暂无 turn 上下文时为 NULL）
    tool_name VARCHAR(128) NOT NULL,
    tool_call_id VARCHAR(128),
    arguments JSONB,
    result JSONB,
    status VARCHAR(16) NOT NULL,     -- pending, success, error, timeout
    error_message TEXT,
    error_type VARCHAR(32),          -- network_error, timeout, invalid_args, execution_failed
    started_at TIMESTAMPTZ NOT NULL,
    completed_at TIMESTAMPTZ,
    duration_ms BIGINT,
    identity_hash VARCHAR(64),
    model VARCHAR(128),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    partition_date DATE NOT NULL DEFAULT CURRENT_DATE,
    PRIMARY KEY (id, partition_date),
    UNIQUE (execution_id, partition_date)
) PARTITION BY RANGE (partition_date);


