// Package sanitizerules manages validated, versioned sanitization policies.
// Published snapshots are immutable: consumers must not modify their Rules or Regex.
package sanitizerules

import (
	"context"
	"errors"
	"regexp"
	"time"
)

var (
	ErrConflict = errors.New("sanitize rule version conflict")
	ErrNotFound = errors.New("sanitize rule record not found")
	ErrInvalid  = errors.New("invalid sanitize rule configuration")
)

type Sample struct {
	Text  string `json:"text"`
	Match bool   `json:"match"`
}
type Rule struct {
	ID         string   `json:"id"`
	Name       string   `json:"name"`
	Type       string   `json:"type"`
	Kind       string   `json:"kind"`
	Pattern    string   `json:"pattern"`
	Group      int      `json:"group"`
	Scopes     []string `json:"scopes"`
	Action     string   `json:"action"`
	Enabled    bool     `json:"enabled"`
	Priority   int      `json:"priority"`
	TenantID   string   `json:"tenant_id,omitempty"`
	Tools      []string `json:"tools,omitempty"`
	Fields     []string `json:"fields,omitempty"`
	Samples    []Sample `json:"samples,omitempty"`
	Exemptions []string `json:"exemptions,omitempty"`
}
type Config struct {
	Rules []Rule `json:"rules"`
}
type CompiledRule struct {
	Rule
	Regex *regexp.Regexp `json:"-"`
}
type Snapshot struct {
	Version      int64          `json:"version"`
	ConfigDigest string         `json:"config_digest"`
	Rules        []CompiledRule `json:"rules"`
}
type ReviewLink struct {
	ID       int64  `json:"id"`
	TenantID string `json:"tenant_id"`
}
type Version struct {
	ID          int64        `json:"id"`
	ParentID    int64        `json:"parent_id"`
	RollbackOf  int64        `json:"rollback_of,omitempty"`
	Config      Config       `json:"config"`
	Actor       string       `json:"actor"`
	Comment     string       `json:"comment"`
	CreatedAt   time.Time    `json:"created_at"`
	ReviewLinks []ReviewLink `json:"review_links,omitempty"`
}

// Event carries metadata only. SampleMasked, Fingerprint and all aggregation/review
// fields supplied to RecordEvent are ignored and regenerated by the store.
// Type and Field must be structural identifiers, never request values.
type Event struct {
	ID              int64      `json:"id"`
	Fingerprint     string     `json:"fingerprint"`
	TenantID        string     `json:"tenant_id"`
	RuleID          string     `json:"rule_id"`
	Version         int64      `json:"version"`
	Phase           string     `json:"phase"`
	Action          string     `json:"action"`
	Type            string     `json:"type,omitempty"`
	Field           string     `json:"field,omitempty"`
	Status          string     `json:"status"`
	SampleMasked    string     `json:"sample_masked"`
	Count           int64      `json:"count"`
	FirstSeen       time.Time  `json:"first_seen"`
	LastSeen        time.Time  `json:"last_seen"`
	Reviewer        string     `json:"reviewer,omitempty"`
	ReviewComment   string     `json:"review_comment,omitempty"`
	ReviewedAt      *time.Time `json:"reviewed_at,omitempty"`
	ResolvedVersion int64      `json:"resolved_version,omitempty"`
}
type EventFilter struct {
	TenantID string
	Status   string
	Action   string
	Limit    int
}
type Instance struct {
	InstanceID   string    `json:"instance_id"`
	Version      int64     `json:"version"`
	ConfigDigest string    `json:"config_digest"`
	LastSeen     time.Time `json:"last_seen"`
	LastRefresh  time.Time `json:"last_refresh"`
	Error        string    `json:"error"`
}

// Store never creates schema. Provision SchemaSQL using the existing migration path.
// Publish atomically checks head, appends history, links reviewed events and advances head.
type Store interface {
	Current(context.Context) (Version, error)
	GetVersion(context.Context, int64) (Version, error)
	ListVersions(context.Context, int) ([]Version, error)
	Publish(context.Context, int64, Config, string, string, int64, ...ReviewLink) (Version, error)
	RecordEvent(context.Context, Event, int) error
	ListEvents(context.Context, EventFilter) ([]Event, error)
	GetEvent(context.Context, int64) (Event, error)
	ReviewEvent(context.Context, string, int64, string, string, string) (Event, error)
	Heartbeat(context.Context, Instance) error
	ListInstances(context.Context) ([]Instance, error)
}
type Notifications interface {
	Publish(context.Context, int64) error
	Subscribe(context.Context) (<-chan int64, error)
}
type Options struct {
	InstanceID string
	// BaselineLoader is consulted only when the DB has no published head.
	// An error retains the local fallback and is retried by background polling.
	BaselineLoader func(context.Context) (Config, error)
	PollInterval   func() time.Duration
	AuditEnabled   func() bool
	EventLimit     func() int
	Notifications  Notifications
	OnError        func(error)
	QueueSize      int
}
